export function normalizeLocale(locale) {
  var raw = String(locale || "").toLowerCase();
  if (raw.startsWith("en")) return "en-US";
  if (raw.startsWith("es")) return "es-ES";
  if (raw.startsWith("zh")) return "zh-CN";
  return "pt-BR";
}

export function getClientLocale() {
  try {
    if (typeof document !== "undefined") {
      var cookieMatch = document.cookie.match(/(?:^|;\s*)syntexa_locale=([^;]+)/);
      if (cookieMatch && cookieMatch[1]) {
        var cookieLocale = normalizeLocale(decodeURIComponent(cookieMatch[1]));
        if (cookieLocale) return cookieLocale;
      }
    }
  } catch {}
  try {
    if (typeof window !== "undefined" && window.localStorage) {
      var stored = window.localStorage.getItem("syntexa_locale");
      if (stored) {
        var storedLocale = normalizeLocale(stored);
        if (storedLocale) return storedLocale;
      }
    }
  } catch {}
  try {
    if (typeof navigator !== "undefined" && navigator.language) {
      return normalizeLocale(String(navigator.language));
    }
  } catch {}
  return DEFAULT_LOCALE;
}

export function t(key, locale) {
  var loc = normalizeLocale(locale || getClientLocale());
  var table = DICT[loc] || DICT[DEFAULT_LOCALE];
  var translation = table[key] || DICT[DEFAULT_LOCALE][key];
  if (!translation) {
    console.warn(`[i18n] Missing translation key: "${key}" for locale: "${loc}"`);
    return DICT[DEFAULT_LOCALE][key] || `[${key}]`;
  }
  return translation;
}

export function formatDateTime(value, locale, options) {
  var loc = normalizeLocale(locale || getClientLocale());
  try {
    return new Date(value).toLocaleString(loc, options || {});
  } catch {
    return "";
  }
}

export function formatNumber(value, locale) {
  var loc = normalizeLocale(locale || getClientLocale());
  try {
    return new Intl.NumberFormat(loc).format(Number(value || 0));
  } catch {
    return String(value || 0);
  }
}

export function useLanguage() {
  var locale = getClientLocale();
  return { t, locale };
}
